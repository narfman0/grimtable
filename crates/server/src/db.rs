//! Postgres storage: a small connection pool, schema created at startup.
//! Timestamps are ISO-8601 UTC text so the API shows them unchanged.

use sqlx::postgres::{PgConnectOptions, PgPool, PgPoolOptions};
use std::str::FromStr;
use std::time::Duration;

/// A `timestamptz` SQL expression in the text form every `*_at` column
/// holds, as a literal for `concat!` (sqlx takes only static SQL).
#[macro_export]
macro_rules! utc_text {
    ($e:literal) => {
        concat!("to_char((", $e, r#") AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"')"#)
    };
}

/// `now()` as `*_at` text.
#[macro_export]
macro_rules! now_sql {
    () => {
        $crate::utc_text!("now()")
    };
}

const SCHEMA: &str = r#"
CREATE TABLE IF NOT EXISTS users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    created_at    TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"')
);
CREATE TABLE IF NOT EXISTS sessions (
    token      TEXT PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'),
    expires_at TEXT
);
CREATE TABLE IF NOT EXISTS armies (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name       TEXT NOT NULL,
    kind       TEXT NOT NULL CHECK (kind IN ('def', 'ros')),
    faction_id TEXT,
    points     BIGINT NOT NULL DEFAULT 0,
    body       TEXT NOT NULL,
    created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'),
    updated_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"')
);
CREATE INDEX IF NOT EXISTS armies_user ON armies(user_id);
CREATE TABLE IF NOT EXISTS games (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    join_code    TEXT NOT NULL UNIQUE,
    visibility   TEXT NOT NULL CHECK (visibility IN ('open', 'closed')),
    status       TEXT NOT NULL CHECK (status IN ('waiting', 'playing', 'finished', 'cancelled')),
    pattern      TEXT NOT NULL,
    points_limit BIGINT NOT NULL,
    host_id      BIGINT NOT NULL REFERENCES users(id),
    seed         BIGINT,
    state_json   TEXT,
    winner       BIGINT,
    created_at   TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'),
    updated_at   TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"')
);
CREATE TABLE IF NOT EXISTS game_players (
    game_id BIGINT NOT NULL REFERENCES games(id) ON DELETE CASCADE,
    seat    BIGINT NOT NULL CHECK (seat IN (0, 1)),
    user_id BIGINT NOT NULL REFERENCES users(id),
    army_id BIGINT NOT NULL REFERENCES armies(id),
    PRIMARY KEY (game_id, seat)
);
CREATE TABLE IF NOT EXISTS game_actions (
    game_id     BIGINT NOT NULL REFERENCES games(id) ON DELETE CASCADE,
    seq         BIGINT NOT NULL,
    seat        BIGINT NOT NULL,
    action_json TEXT NOT NULL,
    created_at  TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'),
    PRIMARY KEY (game_id, seq)
);
"#;

/// Open a pool on a `postgres://` URL and create the schema.
pub async fn connect(url: &str) -> anyhow::Result<PgPool> {
    connect_with(PgConnectOptions::from_str(url)?).await
}

/// As [`connect`], from options (the tests pin a `search_path` per test).
pub async fn connect_with(opts: PgConnectOptions) -> anyhow::Result<PgPool> {
    let pool = PgPoolOptions::new()
        .max_connections(5)
        // Shorter than Neon's five-minute idle cutoff: we close a pooled
        // connection before the server drops it under us.
        .idle_timeout(Duration::from_secs(240))
        .acquire_timeout(Duration::from_secs(30))
        .connect_with(opts)
        .await?;
    sqlx::raw_sql(SCHEMA).execute(&pool).await?;
    Ok(pool)
}
